// ── 1. Удаляем старые товары ─────────────────────────────────────────────────

const OLD_PRODUCTS = ['braslet-vesna', 'shkatulka-luna', 'wer'];
OLD_PRODUCTS.forEach(id => {
  const dir = path.join(PRODUCTS_DIR, id);
  if (fs.existsSync(dir)) {
    fs.rmSync(dir, { recursive: true });
    console.log(`Удалён: ${id}`);
  }
});

// ── 2. Обновляем taxonomy.json ────────────────────────────────────────────────

const taxonomy = JSON.parse(fs.readFileSync(TAXONOMY_FILE, 'utf8'));

// Разделы: Гипс уже есть, оставляем как есть
// Категории: заменяем на новые (старые Браслеты/Кулоны относились к удалённым товарам)
taxonomy.categories = ['Подносы', 'Шкатулки', 'Стаканы', 'Подсвечники', 'Вазы и декор'];

// Подборка Новогодняя уже есть, прочие оставляем
fs.writeFileSync(TAXONOMY_FILE, JSON.stringify(taxonomy, null, 2));
console.log('taxonomy.json обновлён');

// ── 3. Создаём товары ─────────────────────────────────────────────────────────

const usedSlugs = new Set();

RAW.forEach(([name, rawPrice, category, ng]) => {
  const price = Math.ceil(rawPrice / 100) * 100;

  // Генерируем уникальный slug
  let base = toSlug(name);
  let slug = base;
  let i = 2;
  while (usedSlugs.has(slug)) {
    slug = `${base}-${i++}`;
  }
  usedSlugs.add(slug);

  const dir = path.join(PRODUCTS_DIR, slug);
  fs.mkdirSync(path.join(dir, 'images'), { recursive: true });

  const data = {
    name,
    sections: ['Гипс'],
    collections: ng ? ['Новогодняя'] : [],
    categories: [category],
    description: DESCRIPTIONS[name] || '',
    price,
    availability: 'on_order',
    visible: true,
    imageOrder: [],
    createdAt: new Date().toISOString()
  };

  fs.writeFileSync(
    path.join(dir, 'product.json'),
    JSON.stringify(data, null, 2)
  );
  console.log(`  ${slug}  →  ${name}  (${price}₽)${ng ? ' [НГ]' : ''}`);
});

console.log('\nГотово!');
